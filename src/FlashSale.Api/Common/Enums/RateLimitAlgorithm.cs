namespace FlashSale.Api.Common.Enums;

/// <summary>
/// 限流演算法。計畫 §12 要求比較四種，因此做成可切換。
/// </summary>
public enum RateLimitAlgorithm
{
    /// <summary>
    /// 固定視窗：每 N 秒重置一次計數。
    ///
    /// 最簡單、記憶體最省，但有**邊界爆發**問題：
    /// 視窗結束前用滿額度、視窗一開始再用滿一次，
    /// 短短一瞬間就能通過兩倍的請求量。見 docs/rate-limit.md §5.3。
    /// </summary>
    FixedWindow = 0,

    /// <summary>
    /// 滑動視窗：把視窗切成若干區段，隨時間逐段淘汰。
    ///
    /// 解決固定視窗的邊界爆發，代價是要記住每個區段的計數。
    /// </summary>
    SlidingWindow = 1,

    /// <summary>
    /// 權杖桶：以固定速率補充權杖，請求消耗權杖。
    ///
    /// 唯一**允許突發**的演算法 —— 桶裡累積的權杖可以一次用掉。
    /// 適合「平均速率要限制，但短暫突發是正常行為」的場景。
    /// </summary>
    TokenBucket = 2,

    /// <summary>
    /// 併發限制：限制的是「同時進行中的請求數」，不是速率。
    ///
    /// 與前三者是不同維度的東西：前三者管「多久內幾次」，
    /// 這個管「同一時間幾個」。保護的是下游資源的併發容量
    /// （連線池、執行緒），而不是流量本身。
    /// </summary>
    Concurrency = 3
}
